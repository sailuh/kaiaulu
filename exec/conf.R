  "  --sample-size=3",
  "  --max-forks=0 (0 = no limit)",
  "  dry-run unless --apply is provided",
  sep = "\n"
)

args <- commandArgs(trailingOnly = TRUE)
if (length(args) == 0 || any(args %in% c("-h", "--help"))) {
  cat(usage, "\n")
  quit(save = "no", status = 0)
}

# Parse CLI args, flags only (e.g. --apply) and key-value pairs (e.g. --template=path)
flags <- args[startsWith(args, "--")]

extract_flag_value <- function(flags, key, default_value = NULL) {
  prefix <- paste0("--", key, "=")
  matched <- flags[startsWith(flags, prefix)]
  if (length(matched) == 0) {
    return(default_value)
  }
  sub(prefix, "", matched[[1]])
}

# Resolve CLI configuration (source, paths, modes)
source_mode <- tolower(extract_flag_value(flags, "source", "mysql"))
template_path <- extract_flag_value(flags, "template", "conf/trinitycore.yml") # Default template with all possible fields for GitHub projects
out_dir <- extract_flag_value(flags, "out", "conf")
backup_dir <- extract_flag_value(flags, "backup-dir", NULL)
apply_changes <- "--apply" %in% flags
verbose <- "--verbose" %in% flags
prune_out_of_scope <- !("--no-prune" %in% flags)
verify_api <- "--verify-api" %in% flags
token_path <- extract_flag_value(flags, "token-path", "~/.ssh/github_token") # Default path for GitHub token used in API validation
sample_size <- as.integer(extract_flag_value(flags, "sample-size", "3"))
max_forks <- as.integer(extract_flag_value(flags, "max-forks", "0"))

if (source_mode != "mysql") {
  stop("--source must be mysql")
}

if (!file.exists(template_path)) {
  stop("Template YAML not found: ", template_path)
}
if (!dir.exists(out_dir)) {
  stop("Output directory not found: ", out_dir)
}
if (!is.null(backup_dir) && !dir.exists(backup_dir) && apply_changes) {
  dir.create(backup_dir, recursive = TRUE, showWarnings = FALSE)
}

