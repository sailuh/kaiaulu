# Build CLI usage/help text for -h/--help
usage <- paste(
  "USAGE:",
  "  Rscript exec/conf.R [--source=mysql] [--template=<template_yml>] [--out=<conf_dir>] [--apply] [--no-prune] [--verify-api] [--token-path=<path>] [--sample-size=<n>] [--max-forks=<n>] [--verbose]",
  "",
  "DESCRIPTION:",
  "  Generates YAML configs using MySQL with canonical + fork-only policy.",
  "",
  "  Naming policy:",
  "    - repo.yml if owner == repo",
  "    - repo_owner.yml otherwise",
  "",
  "  Output policy:",
  "    - writes files into conf/ by default",
  "    - backup-then-replace for existing target files",
  "    - deletes out-of-scope YAML files only if previously generated by this script",
  "",
  "MYSQL ENV VARS:",
  "  MYSQL_HOST, MYSQL_PORT, MYSQL_DB, MYSQL_USER, MYSQL_PASSWORD",
